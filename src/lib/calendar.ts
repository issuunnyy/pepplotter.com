export interface CalendarEventParams {
  compoundName: string;
  doseDisplay: string; // e.g. "250 mcg (0.25 mg)"
  syringeUnits: number;
  syringeType: string;
  drawVolumeMl: number;
  frequencyDays: number; // e.g. 7 for weekly, 3.5 for split
  totalWeeks?: number;
  startDate?: Date;
}

/**
 * 生成 RRULE。目标跨度固定 8 周。
 * 注意：FREQ=DAILY 的 INTERVAL 必须是整数，无法表达 3.5 天这类半周节奏，
 * 因此统一改用 HOURLY;INTERVAL=频率*24，既精确又符合 RFC 5545。
 */
function buildRRule(frequencyDays: number): string {
  const spanDays = 56; // 8 周
  const intervalHours = Math.max(1, Math.round(frequencyDays * 24));
  const count = Math.max(1, Math.ceil(spanDays / frequencyDays));
  return `RRULE:FREQ=HOURLY;INTERVAL=${intervalHours};COUNT=${count}`;
}

/**
 * Format a Date to iCalendar compact ISO string (YYYYMMDDTHHMMSSZ)
 */
function toICalDate(date: Date): string {
  return date.toISOString().replace(/[-:]/g, '').split('.')[0] + 'Z';
}

/**
 * RFC 5545 §3.3.11 文本转义。
 * 反斜杠、逗号、分号必须转义；换行必须写为字面 `\n` 两字符序列。
 * 不做这一步的话，含逗号的药品名会截断字段并可注入额外属性（如 ATTENDEE），
 * 形成日历邀请注入。
 */
function escapeICalText(value: string): string {
  return String(value)
    .replace(/\\/g, '\\\\')
    .replace(/;/g, '\\;')
    .replace(/,/g, '\\,')
    .replace(/\r\n|\r|\n/g, '\\n');
}

/** 去掉 ASCII 控制字符，避免破坏 iCalendar 行结构导致解析器截断文件 */
function stripControlChars(value: string): string {
  return String(value).replace(/[\x00-\x08\x0B\x0C\x0E-\x1F\x7F]/g, '');
}

/**
 * Generate a direct Google Calendar Web Link (Gmail / Google Calendar)
 */
export function generateGoogleCalendarUrl(params: CalendarEventParams): string {
  const start = params.startDate ? new Date(params.startDate) : new Date();
  start.setHours(9, 0, 0, 0); // 9:00 AM
  const end = new Date(start.getTime() + 15 * 60 * 1000); // 15 mins later

  const startIso = toICalDate(start);
  const endIso = toICalDate(end);

  const title = `💉 ${stripControlChars(params.compoundName)} Administration (${params.syringeUnits} Units)`;
  
  const details = [
    `Protocol Details (${params.compoundName}):`,
    `• Target Dose: ${params.doseDisplay}`,
    `• Draw to: ${params.syringeUnits} Units (${params.drawVolumeMl} mL on ${params.syringeType})`,
    `• Administration Route: Subcutaneous Injection`,
    `• Storage: Keep reconstituted vial refrigerated at 36°F - 46°F (2°C - 8°C)`,
    `• Reminder Generated by PepPlotter (https://pepplotter.com)`,
  ].join('\n');

  // Recurrence rule
  const rrule = buildRRule(params.frequencyDays);

  const query = new URLSearchParams({
    action: 'TEMPLATE',
    text: title,
    dates: `${startIso}/${endIso}`,
    details: details,
    recur: rrule,
    location: 'Home / Clinic',
  });

  return `https://calendar.google.com/calendar/render?${query.toString()}`;
}

/**
 * Generate iCalendar (.ics) file content for Apple Calendar (iOS / Mac) and Outlook
 */
export function generateIcsContent(params: CalendarEventParams): string {
  const start = params.startDate ? new Date(params.startDate) : new Date();
  start.setHours(9, 0, 0, 0);
  const end = new Date(start.getTime() + 15 * 60 * 1000);

  const startIso = toICalDate(start);
  const endIso = toICalDate(end);
  const nowIso = toICalDate(new Date());

  const freq = buildRRule(params.frequencyDays);

  // ICS 文本字段全部走RFC 5545 转义；标题去掉 emoji（部分解析器非 UTF-8 兼容）
  const title = escapeICalText(`${stripControlChars(params.compoundName)} Dose (${params.syringeUnits} Units)`);
  const description = escapeICalText(
    [
      `Target Dose: ${params.doseDisplay}`,
      `Draw to: ${params.syringeUnits} Units (${params.drawVolumeMl} mL on ${params.syringeType})`,
      'Keep refrigerated 2-8C',
      'PepPlotter Protocol',
    ].join('\n')
  );

  return [
    'BEGIN:VCALENDAR',
    'VERSION:2.0',
    'PRODID:-//PepPlotter//Dosing Schedule Reminder//EN',
    'CALSCALE:GREGORIAN',
    'METHOD:PUBLISH',
    'BEGIN:VEVENT',
    `UID:pepplotter-${Date.now()}-${Math.random().toString(36).slice(2, 10)}@pepplotter.com`,
    `DTSTAMP:${nowIso}`,
    `DTSTART:${startIso}`,
    `DTEND:${endIso}`,
    freq,
    `SUMMARY:${title}`,
    `DESCRIPTION:${description}`,
    'LOCATION:Home / Clinic',
    'STATUS:CONFIRMED',
    'BEGIN:VALARM',
    'TRIGGER:-PT15M',
    'ACTION:DISPLAY',
    'DESCRIPTION:Peptide Injection Reminder',
    'END:VALARM',
    'END:VEVENT',
    'END:VCALENDAR',
  ].join('\r\n');
}

/**
 * Download .ics file directly in browser
 */
export function downloadIcsFile(params: CalendarEventParams): void {
  const content = generateIcsContent(params);
  // ﻿BOM：确保 Outlook /旧版日历按 UTF-8 解析中文药品名
  const blob = new Blob(['﻿' + content], { type: 'text/calendar;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  // 文件名净化：仅保留字母数字与分隔符，避免非法字符或路径穿越
  const safeName = stripControlChars(params.compoundName)
    .replace(/[^a-zA-Z0-9._-]/g, '-')
    .replace(/-+/g, '-')
    .slice(0, 60) || 'peptide';
  const link = document.createElement('a');
  link.href = url;
  link.setAttribute('download', `${safeName.toLowerCase()}-schedule.ics`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  // 延迟释放：部分浏览器在 click 后仍需同步读取 blob
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
